"""COURSE-ALIVE2 automatic verification of the PS2 bird port (36 courses).

Checks (PASS / FAIL / NOT_PERFORMED):
1. asset: regenerated bytes equal the private asset and the digest pinned in ps2_birds_pilot.hpp;
2. configuration: every one of the 36 PS2 RaceTest XML has one BirdManager; distances, RndFly/RndMil (clamp <=10), list
   presence and FlightList points in the asset equal the AMBIENT2 typed reader; the update gate (both lists) is open on
   exactly the courses with a local MillList;
3. resources: the four 16x16 cells equal the BURDYBROWN_000.GXI sprite band in PS2 VRAM row order, alpha binary; the four
   frames equal the PSB triangles (keys 0..3, two triangles each, UV inside one cell);
4. reference: the C++ manager (tests/ps2_birds_tests.cpp --dump) equals tools/ps2_bird_model.py bit for bit on all 36
   courses over TICKS game ticks of a fixed synthetic camera path: RNG state, clock, cache, counts, every entity
   (flying flag, image key, en2d and carrier XYZ) and every drawn world vertex;
5. lifecycle: a restarted manager repeats the same timeline (no state survives a race restart); a closed gate consumes no RNG.

    python ps2-research/pc-port/tools/verify_ps2_birds.py [--report docs/course-alive2/verification.json]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PORT / 'tools'))
import prepare_ps2_birds as prep  # noqa: E402
import ps2_bird_model as model  # noqa: E402
from ps2_bird_model import br, f32, add, sub, mul, div  # noqa: E402

TICKS = 18000                     # 10 minutes at 30 ticks per second
TEST_EXE = PORT / '.build' / 'ps2-enabled' / 'Release' / 'ps2_birds_tests.exe'
ENTITY = struct.Struct('<Bb2x3f3f')
TICK = struct.Struct('<If4Bi')
BITS = struct.Struct('<f')


def bits(v):
    return BITS.pack(v)


def norm3(v):
    n = f32(math.sqrt(add(add(mul(v[0], v[0]), mul(v[1], v[1])), mul(v[2], v[2]))))
    return tuple(div(x, n) for x in v)


def camera_path(points):
    """Synthetic camera: along the FlightList polyline (or the X axis) at 0.6 units per tick, 3 units up, looking along
    the path and slightly down. It only drives the comparison; it is not a recorded race."""
    pts = [tuple(p) for p in points] or [(0., 0., 0.), (500., 0., 0.)]
    if len(pts) == 1:
        pts = pts + [(pts[0][0] + 500., pts[0][1], pts[0][2])]
    loop = pts + pts[::-1][1:]
    out, seg, t = [], 0, 0.
    for _ in range(TICKS):
        a, b = loop[seg % (len(loop) - 1)], loop[seg % (len(loop) - 1) + 1]
        d = math.dist(a, b) or 1.
        p = tuple(f32(a[i] + (b[i] - a[i]) * t / d) for i in range(3))
        look = norm3((f32(b[0] - a[0] or 1.), f32(-0.15 * d), f32(b[2] - a[2])))
        side = norm3((look[2], 0., -look[0]))
        up = norm3((sub(mul(side[1], look[2]), mul(side[2], look[1])), sub(mul(side[2], look[0]), mul(side[0], look[2])),
                    sub(mul(side[0], look[1]), mul(side[1], look[0]))))
        if up[1] < 0:
            up = tuple(-x for x in up)
        out.append(((p[0], add(p[1], 3.), p[2]), look, up))
        t += .6
        if t >= d:
            t -= d
            seg += 1
    return out


class Report:
    def __init__(self):
        self.checks = {}

    def set(self, name, status, **detail):
        self.checks[name] = {'status': status, **detail}
        print(f'{status:14} {name} {json.dumps(detail)[:300]}', flush=True)


def course_cfg(r):
    return model.CourseBirds(flight=[br.xyz(p) for p in r['flight_points']] if r['flight_present'] else None,
                             mill_present=r['mill_present'], min_fly=f32(r['min_fly']), max_fly=f32(r['max_fly']), rnd_fly=r['rnd_fly'])


def reference(r, cams):
    m = model.Manager(course_cfg(r))
    rows, verts = [], []
    for cam, look, up in cams:
        m.tick(cam)
        ents = [(int(e.bird is not None), e.switch.frame if e.switch else 0, e.en2d, e.carrier) for e in m.entities]
        rows.append((m.rng.state, m.clock, len(m.free), len(m.pending), len(m.flying), m.cache, ents))
        side = model.camera_basis(look, up)
        rr = model.billboard(side, look)
        tick_verts = []
        for e, pos, key in m.snapshot():
            for tri in FRAMES[key]['triangles']:
                for vx, vy in tri['xy']:
                    tick_verts.append(_vertex(pos, rr, vx, vy))
        verts.append(tick_verts)
    return rows, verts, m


def _vertex(pos, rows, vx, vy):
    lx, ly = model.frame_local(vx, vy)
    return model.world_vertex(pos, rows, lx, ly)


FRAMES = []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--report', type=Path)
    a = ap.parse_args()
    rep = Report()
    bank, rows = prep.bank(), prep.courses()
    FRAMES.extend(bank['frames'])
    blob = prep.build(bank, rows)
    digest = hashlib.sha256(blob).hexdigest()
    on_disk = prep.ASSET.read_bytes() if prep.ASSET.exists() else b''
    pinned = (PORT / 'renderer' / 'ps2_birds_pilot.hpp').read_text(encoding='utf-8').split('kPS2BirdsArtifactSha[]="')[1][:64]
    rep.set('asset_deterministic_and_pinned', 'PASS' if blob == on_disk and digest == pinned else 'FAIL', sha256=digest, bytes=len(blob))

    # 2. configuration
    import course_config as cc
    ok, table = True, []
    for c, r in zip(cc.courses(), rows):
        doc = br.parse_authored(cc.read_ps2(c.ps2_xml), c.ps2_xml)
        m = doc['managers'][0]
        k = m['resolved_config']
        same = (r['min_fly'], r['max_fly'], r['min_mil'], r['max_mil'], r['rnd_fly'], r['rnd_mil']) == \
               (k['Min Fly Dist'], k['Max Fly Dist'], k['Min Mil Dist'], k['Max Mil Dist'], k['Rnd Fly'], k['Rnd Mil'])
        pts = [x['position'] for x in m['lists']['flight']] if m['lists']['flight'] else []
        same &= [tuple(bits(v) for v in p) for p in pts] == [tuple(bits(v) for v in p) for p in r['flight_points']]
        same &= r['flight_present'] == (m['lists']['flight'] is not None) and r['mill_present'] == (m['lists']['milling'] is not None)
        ok &= same and len(doc['managers']) == 1
        table.append({'course': r['name'], 'flight_points': len(r['flight_points']), 'mill_list': r['mill_present'],
                      'update_gate': 'open' if r['flight_present'] and r['mill_present'] else 'closed', 'min_fly': r['min_fly'],
                      'max_fly': r['max_fly'], 'rnd_fly': r['rnd_fly'], 'equal_to_ps2_xml': same})
    gates = sum(1 for t in table if t['update_gate'] == 'open')
    rep.set('configuration_36_courses', 'PASS' if ok and len(rows) == 36 and gates == 10 else 'FAIL', courses=len(rows), open_gate=gates,
            open=[t['course'] for t in table if t['update_gate'] == 'open'])

    # 3. resources
    gxi = prep.cc.read_ps2(bank['gxi'])[8:]
    cells_ok = True
    for ci, cell in enumerate(bank['cells']):
        for r_ in range(16):
            for x in range(16):
                fr = 63 - (48 + r_)
                rr, gg, bb, aa = gxi[(fr * 64 + ci * 16 + x) * 4:(fr * 64 + ci * 16 + x) * 4 + 4]
                cells_ok &= cell[(r_ * 16 + x) * 4:(r_ * 16 + x) * 4 + 4] == bytes((bb, gg, rr, 255 if aa else 0))
    opaque = sum(1 for cell in bank['cells'] for i in range(3, len(cell), 4) if cell[i])
    frames_ok = [f['key'] for f in bank['frames']] == [0, 1, 2, 3] and all(len(f['triangles']) == 2 for f in bank['frames'])
    rep.set('resources_burdy_bank', 'PASS' if cells_ok and frames_ok and opaque == bank['gxi_alpha_nonzero'] else 'FAIL',
            cells_equal_gxi=cells_ok, opaque_texels=opaque, gxi_opaque=bank['gxi_alpha_nonzero'],
            frame_cells=[f['cell'] for f in bank['frames']], psb_sha256=bank['psb_sha256'], gxi_sha256=bank['gxi_sha256'])

    # 4. reference
    cams_all = [camera_path(r['flight_points']) for r in rows]
    stats = {}
    if not TEST_EXE.exists():
        rep.set('cpp_equals_reference', 'NOT_PERFORMED', reason=f'{TEST_EXE} missing (build the overlay first)')
    else:
        with tempfile.TemporaryDirectory() as tmp:
            cam_path, out_path = Path(tmp) / 'cams.bin', Path(tmp) / 'dump.bin'
            cam_path.write_bytes(b''.join(struct.pack('<9f', *c, *l, *u) for cams in cams_all for c, l, u in cams))
            subprocess.run([str(TEST_EXE), '--dump', str(prep.ASSET), str(TICKS), str(cam_path), str(out_path)], check=True)
            dump = out_path.read_bytes()
        at, mismatches, compared_ticks, compared_vertices = 0, [], 0, 0
        for r, cams in zip(rows, cams_all):
            ref_rows, ref_verts, m = reference(r, cams)
            first, peak, bird_ticks = None, 0, 0
            for t in range(TICKS):
                head = TICK.unpack_from(dump, at); at += TICK.size
                ents = [ENTITY.unpack_from(dump, at + i * ENTITY.size) for i in range(model.POOL)]; at += ENTITY.size * model.POOL
                rr = ref_rows[t]
                same = head[0] == rr[0] and bits(head[1]) == bits(rr[1]) and head[2:5] == rr[2:5] and head[6] == rr[5]
                for (fl, key, *xyz), (rfl, rkey, en2d, carrier) in zip(ents, rr[6]):
                    same &= fl == rfl and (key == rkey or not fl) and all(bits(x) == bits(y) for x, y in zip(xyz, (*en2d, *carrier)))
                nv = len(ref_verts[t])
                got = [struct.unpack_from('<3f', dump, at + i * 12) for i in range(nv)]; at += 12 * nv
                same &= all(bits(x) == bits(y) for g, w in zip(got, ref_verts[t]) for x, y in zip(g, w))
                compared_ticks += 1; compared_vertices += nv
                if not same and len(mismatches) < 5:
                    mismatches.append({'course': r['name'], 'tick': t + 1, 'cpp': list(head), 'reference': list(rr[:6])})
                elif not same:
                    mismatches.append(None)
                if rr[4]:
                    bird_ticks += 1; peak = max(peak, rr[4])
                    if first is None:
                        first = t + 1
            stats[r['name']] = {'first_flying_tick': first, 'first_flying_seconds': round(first / 30., 1) if first else None,
                                'peak_flying': peak, 'ticks_with_birds': bird_ticks, 'rng_calls': m.rng.calls}
        if at != len(dump):
            mismatches.append({'error': 'dump size'})
        rep.set('cpp_equals_reference', 'PASS' if not mismatches else 'FAIL', courses=len(rows), ticks_per_course=TICKS,
                compared_ticks=compared_ticks, compared_world_vertices=compared_vertices, mismatches=len(mismatches),
                first=[x for x in mismatches if x][:3])

    # 5. lifecycle
    open_course = next(r for r in rows if r['flight_present'] and r['mill_present'] and r['flight_points'])
    closed_course = next(r for r in rows if not r['mill_present'])
    cams = camera_path(open_course['flight_points'])[:3000]
    a1, a2 = model.Manager(course_cfg(open_course)), model.Manager(course_cfg(open_course))
    for c, _, _ in cams:
        a1.tick(c)
    for c, _, _ in cams:
        a2.tick(c)
    restart_same = a1.rng.state == a2.rng.state and a1.snapshot() == a2.snapshot()
    z = model.Manager(course_cfg(closed_course))
    for c, _, _ in camera_path(closed_course['flight_points'])[:3000]:
        z.tick(c)
    closed_quiet = z.rng.calls == 0 and not z.flying and len(z.free) == model.POOL
    rep.set('lifecycle_restart_and_closed_gate', 'PASS' if restart_same and closed_quiet else 'FAIL', restart_identical=restart_same,
            closed_gate_no_rng_no_birds=closed_quiet, open_case=open_course['name'], closed_case=closed_course['name'])

    overall = 'PASS' if all(v['status'] == 'PASS' for v in rep.checks.values()) else (
        'FAIL' if any(v['status'] == 'FAIL' for v in rep.checks.values()) else 'PARTIAL')
    result = {'schema_version': 1, 'phase': 'COURSE-ALIVE2', 'asset_sha256': digest, 'overall': overall, 'checks': rep.checks,
              'courses': table, 'synthetic_camera_statistics': stats,
              'note': 'statistics come from a synthetic camera path along each FlightList and a fixed RNG seed; they are not a recorded PS2 race'}
    if a.report:
        a.report.write_text(json.dumps(result, indent=1) + '\n', encoding='utf-8')
    print('OVERALL', overall)
    return 0 if overall == 'PASS' else 1


if __name__ == '__main__':
    sys.exit(main())
