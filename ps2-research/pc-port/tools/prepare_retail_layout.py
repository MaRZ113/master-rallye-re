"""RETAIL-DERIVATIVE1: page table of the retail MRallye.exe for renderer/retail_layout_table.hpp.

An in-place mod of the retail executable (invitation entries, cooked course builds) keeps the file size, the PE image
base and the section layout and changes a few 4 KiB pages. The proxy compares a running EXE with this table
(renderer/retail_layout.hpp) when RetailDerivativeBuilds=1: same size, same image base and section table, at most
kMaxChangedPages changed pages -> RETAIL_DERIVATIVE, and the changed pages are logged.

    python ps2-research/pc-port/tools/prepare_retail_layout.py [--exe <retail MRallye.exe>] [--check <exe> ...]
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
OUT = PORT / 'renderer' / 'retail_layout_table.hpp'
RETAIL_SHA = 'bf8aef32407eb6552c05045b8abef149f32983cedd9503b865069b444c5f96b4'
PAGE = 4096


def fnv1a64(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def sections(b: bytes):
    pe = struct.unpack_from('<I', b, 0x3c)[0]
    count = struct.unpack_from('<H', b, pe + 6)[0]
    opt = struct.unpack_from('<H', b, pe + 20)[0]
    base = struct.unpack_from('<I', b, pe + 24 + 28)[0]
    out = []
    for i in range(count):
        s = pe + 24 + opt + i * 40
        name = b[s:s + 8]
        _, va, raw_size, raw_ptr = struct.unpack_from('<4I', b, s + 8)
        ch = struct.unpack_from('<I', b, s + 36)[0]
        out.append((name, va, raw_size, raw_ptr, ch))
    return pe, base, out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--exe', type=Path, default=Path('D:/Game/Master Rallye/MRallye.exe'))
    ap.add_argument('--check', type=Path, nargs='*', default=[])
    a = ap.parse_args()
    b = a.exe.read_bytes()
    if hashlib.sha256(b).hexdigest() != RETAIL_SHA:
        raise SystemExit(f'{a.exe} is not the retail executable')
    pe, base, secs = sections(b)
    pages = [fnv1a64(b[i:i + PAGE]) for i in range(0, len(b), PAGE)]
    lines = ['#pragma once',
             '// Generated by tools/prepare_retail_layout.py from the retail MRallye.exe',
             f'// (SHA-256 {RETAIL_SHA}). Do not edit.',
             '#include <array>', '#include <cstdint>', '',
             'namespace gfx2::ps2port::retail {',
             f'inline constexpr uint32_t kFileSize={len(b)}u,kPeOffset={pe}u,kImageBase=0x{base:x}u,kPageSize={PAGE}u;',
             'struct Section { char name[8]; uint32_t va,raw_size,raw_ptr,characteristics; };',
             f'inline constexpr std::array<Section,{len(secs)}> kSections={{{{']
    for name, va, rs, rp, ch in secs:
        chars = ','.join(str(c) for c in name)
        lines.append(f'    {{{{{chars}}},0x{va:x}u,0x{rs:x}u,0x{rp:x}u,0x{ch:x}u}},')
    lines.append('}};')
    lines.append(f'inline constexpr std::array<uint64_t,{len(pages)}> kPageFnv={{{{')
    for i in range(0, len(pages), 6):
        lines.append('    ' + ','.join(f'0x{p:016x}ull' for p in pages[i:i + 6]) + ',')
    lines.append('}};')
    lines.append('} // namespace gfx2::ps2port::retail')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT}: {len(pages)} pages, {len(secs)} sections')
    for path in a.check:
        m = path.read_bytes()
        same = len(m) == len(b) and sections(m) == (pe, base, secs)
        changed = [i * PAGE for i in range(0, len(pages)) if fnv1a64(m[i * PAGE:(i + 1) * PAGE]) != pages[i]] if same else []
        print(path.name, 'layout', 'same' if same else 'DIFFERENT', 'changed pages', len(changed), [hex(x) for x in changed])
    return 0


if __name__ == '__main__':
    sys.exit(main())
